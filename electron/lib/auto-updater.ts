import { app } from "electron"
import { autoUpdater, type UpdateDownloadedEvent } from "electron-updater"
import { ReleaseNotesManager } from "../update/ReleaseNotesManager"
import type { AppState } from "../main"
import { SettingsManager } from "../services/SettingsManager"

let pendingUpdateNotice: UpdateDownloadedEvent | null = null
let lastCheckedAt: number | null = null
let availableVersion: string | null = null
let downloadedVersion: string | null = null
let checking = false

export function getUpdateState() {
  return {
    autoCheck: SettingsManager.getInstance().get('autoCheckUpdates') !== false,
    checking,
    lastCheckedAt,
    availableVersion,
    downloadedVersion
  }
}

export function setupAutoUpdater(appState: AppState): void {
  autoUpdater.autoDownload = true
  autoUpdater.autoInstallOnAppQuit = true

  // Default to latest (stable) channel - matches latest-mac.yml generated by electron-builder
  autoUpdater.channel = 'latest'
  console.log(`[AutoUpdater] Channel: ${autoUpdater.channel}`)

  autoUpdater.on("checking-for-update", () => {
    checking = true
    console.log("[AutoUpdater] Checking for update...")
    appState.broadcast("update-checking")
  })

  autoUpdater.on("update-available", async (info) => {
    checking = false
    lastCheckedAt = Date.now()
    availableVersion = info.version
    console.log("[AutoUpdater] Update available:", info.version)
    appState.updateAvailable = true

    // Fetch structured release notes
    const releaseManager = ReleaseNotesManager.getInstance();
    const notes = await releaseManager.fetchReleaseNotes(info.version);

    // Notify renderer that an update is available with parsed notes if available
    appState.broadcast("update-available", {
      ...info,
      parsedNotes: notes
    })
  })

  autoUpdater.on("update-not-available", (info) => {
    checking = false
    lastCheckedAt = Date.now()
    availableVersion = null
    console.log("[AutoUpdater] Update not available:", info.version)
    appState.broadcast("update-not-available", info)
  })

  autoUpdater.on("error", (err) => {
    checking = false
    console.error("[AutoUpdater] Error:", err)
    // Include more details in the error message for debugging
    const errorMessage = err.message || err.toString() || 'Unknown update error'
    appState.broadcast("update-error", errorMessage)
  })

  autoUpdater.on("download-progress", (progressObj) => {
    let log_message = "Download speed: " + progressObj.bytesPerSecond
    log_message = log_message + " - Downloaded " + progressObj.percent + "%"
    log_message = log_message + " (" + progressObj.transferred + "/" + progressObj.total + ")"
    console.log("[AutoUpdater] " + log_message)
    appState.broadcast("download-progress", progressObj)
  })

  autoUpdater.on("update-downloaded", (info) => {
    downloadedVersion = info.version
    console.log("[AutoUpdater] Update downloaded:", info.version)
    if (appState.getIsMeetingActive()) {
      pendingUpdateNotice = info
    } else {
      appState.broadcast("update-downloaded", info)
    }
  })

  if (app.isPackaged) {
    const checkForUpdates = () => {
      if (SettingsManager.getInstance().get('autoCheckUpdates') === false) return
      autoUpdater.checkForUpdates().catch(err => {
        console.error("[AutoUpdater] Failed to check for updates:", err);
      });
    };
    setTimeout(checkForUpdates, 10000);
    const interval = setInterval(checkForUpdates, 4 * 60 * 60 * 1000);
    // A finished download is offered once; checking again would re-open the modal after "Not Now".
    autoUpdater.once("update-downloaded", () => clearInterval(interval));
  }
}

export function flushPendingUpdateNotice(appState: AppState): void {
  if (!pendingUpdateNotice) return
  const info = pendingUpdateNotice
  pendingUpdateNotice = null
  appState.broadcast("update-downloaded", info)
}

export async function checkForUpdatesManual(appState: AppState): Promise<void> {
  try {
    console.log('[AutoUpdater] Checking for updates manually via GitHub API...');
    const releaseManager = ReleaseNotesManager.getInstance();
    // Fetch latest release
    const notes = await releaseManager.fetchReleaseNotes('latest');

    if (notes) {
      const currentVersion = app.getVersion();
      const latestVersionTag = notes.version; // e.g., "v1.2.0" or "1.2.0"
      const latestVersion = latestVersionTag.replace(/^v/, '');

      console.log(`[AutoUpdater] Manual Check: Current=${currentVersion}, Latest=${latestVersion}`);

      if (isVersionNewer(appState, currentVersion, latestVersion)) {
        console.log('[AutoUpdater] Manual Check: New version found!');
        appState.updateAvailable = true;

        // Mock an info object compatible with electron-updater
        const info = {
          version: latestVersion,
          files: [] as any[],
          path: '',
          sha512: '',
          releaseName: notes.summary,
          releaseNotes: notes.fullBody
        };

        // Notify renderer
        appState.broadcast("update-available", {
          ...info,
          parsedNotes: notes
        });
      } else {
        console.log('[AutoUpdater] Manual Check: App is up to date.');
        appState.broadcast("update-not-available", { version: currentVersion });
      }
    }
  } catch (err) {
    console.error('[AutoUpdater] Manual update check failed:', err);
  }
}

export function isVersionNewer(appState: AppState, current: string, latest: string): boolean {
  // EC-01 fix: strip pre-release suffixes (e.g. "2.1.0-beta.1" → "2.1.0")
  // before splitting so Number() never returns NaN on comparison.
  const stripPre = (v: string) => v.replace(/-.*$/, '');
  const c = stripPre(current).split('.').map(Number);
  const l = stripPre(latest).split('.').map(Number);

  for (let i = 0; i < 3; i++) {
    const cv = c[i] || 0;
    const lv = l[i] || 0;
    if (lv > cv) return true;
    if (lv < cv) return false;
  }
  return false;
}

export async function quitAndInstallUpdate(appState: AppState): Promise<void> {
  console.log('[AutoUpdater] quitAndInstall called - applying update...')

  setImmediate(() => {
    try {
      autoUpdater.quitAndInstall(false, true)
    } catch (err) {
      console.error('[AutoUpdater] quitAndInstall failed:', err)
      app.exit(0)
    }
  })
}

export async function checkForUpdates(appState: AppState): Promise<void> {
  console.log('[AutoUpdater] Manual check for updates requested')
  try {
    // In development mode, use manual GitHub API check (electron-updater skips in dev)
    if (!app.isPackaged) {
      await checkForUpdatesManual(appState)
    } else {
      await autoUpdater.checkForUpdates()
    }
  } catch (err: any) {
    console.error('[AutoUpdater] checkForUpdates failed:', err)
    const errorMessage = err.message || err.toString() || 'Update check failed'
    appState.broadcast("update-error", errorMessage)
  }
}

export function downloadUpdate(appState: AppState): void {
  console.log('[AutoUpdater] Starting download...')
  try {
    // Errors during download are surfaced via autoUpdater.on("error") which
    // already broadcasts "update-error". Do not broadcast here to avoid duplicates.
    autoUpdater.downloadUpdate().catch(err => {
      console.error('[AutoUpdater] downloadUpdate failed:', err)
    })
  } catch (err: any) {
    console.error('[AutoUpdater] downloadUpdate exception:', err)
  }
}
